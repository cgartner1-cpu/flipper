#!/usr/bin/env python3
"""Generate src/ZagreusValley/Generated/Sheets.g.cs from sheets/*.json. One C# record per row. Run preflight first."""
import json, pathlib, re
ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "src/ZagreusValley/Generated/Sheets.g.cs"

def pascal(s): return "".join(p[:1].upper() + p[1:] for p in re.split(r"[_\W]+", s) if p)
def cs_type(vals):
    if all(isinstance(v, bool) for v in vals): return "bool"
    if all(isinstance(v, int) and not isinstance(v, bool) for v in vals): return "int"
    if all(isinstance(v, (int, float)) and not isinstance(v, bool) for v in vals): return "float"
    return "string"
def lit(v, t):
    if t == "bool": return "true" if v else "false"
    if t == "float": return f"{float(v)}f"
    if t == "int": return str(v)
    return json.dumps(str(v))

lines = ["// <auto-generated> from sheets/*.json by tools/gen.py. Edit the sheets, not this file. </auto-generated>",
         "#nullable enable", "using System.Collections.Generic;", "", "namespace ZagreusValley.Generated;", ""]
for p in sorted((ROOT / "sheets").glob("*.json")):
    d = json.loads(p.read_text()); name = pascal(d["sheet"]); rec = name.rstrip("s") + "Row"
    cols = list(d["columns"]); types = {c: cs_type([r[c] for r in d["rows"]]) for c in cols}
    lines.append(f"/// <summary>{d['about']}</summary>")
    lines.append(f"public sealed record {rec}(" + ", ".join(f"{types[c]} {pascal(c)}" for c in cols) + ");")
    lines.append(f"public static class {name}Sheet")
    lines.append("{")
    lines.append(f"    public static readonly IReadOnlyList<{rec}> Rows = new {rec}[]")
    lines.append("    {")
    for r in d["rows"]:
        lines.append(f"        new(" + ", ".join(lit(r[c], types[c]) for c in cols) + "),")
    lines.append("    };")
    lines.append("}")
    lines.append("")
OUT.parent.mkdir(parents=True, exist_ok=True); OUT.write_text("\n".join(lines))
print(f"wrote {OUT.relative_to(ROOT)}")
